  static String? getImageUrl(String productId) {
    if (images.containsKey(productId)) {
      return images[productId];
    }
    
    // Direct exact keyword match
    final cleanId = productId.toLowerCase();
    for (final entry in images.entries) {
      if (cleanId == entry.key || cleanId.startsWith(entry.key) || entry.key.startsWith(cleanId)) {
        return entry.value;
      }
    }
    
    // Secondary keyword match
    for (final entry in images.entries) {
      if (cleanId.contains(entry.key) || entry.key.contains(cleanId)) {
        return entry.value;
      }
    }
    return null;
  }
