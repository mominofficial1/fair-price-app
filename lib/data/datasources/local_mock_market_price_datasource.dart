  @override
  Future<List<MarketPrice>> getPrices({
    required String division,
    String? district,
    String? upazila,
    String? marketId,
    DateTime? date,
  }) async {
    final effectiveMarketId = marketId ?? 'rajshahi_shaheb_bazar';
    final locationData = LocationDataSource.getLocationById(effectiveMarketId);
    final modifier = locationData?.priceModifier ?? 1.0;

    final now = DateTime.now();
    return _baseProducts.map((p) {
      final damPrice = (p['damBase'] as double) * modifier;
      final marketAvg = (p['marketBase'] as double) * modifier;
      final minPrice = (p['minBase'] as double) * modifier;
      final maxPrice = (p['maxBase'] as double) * modifier;
      final wholesale = (p['wholesaleBase'] as double) * modifier;

      return MarketPrice(
        id: '${p['productId']}_$effectiveMarketId',
        productId: p['productId'] as String,
        productNameBn: p['nameBn'] as String,
        productNameEn: p['nameEn'] as String,
        category: p['category'] as String,
        icon: p['icon'] as String,
        division: locationData?.divisionId ?? division,
        district: locationData?.districtId ?? 'rajshahi_dist',
        upazila: locationData?.upazilaId ?? 'boalia',
        marketId: effectiveMarketId,
        marketNameBn: locationData?.nameBn ?? 'সাহেব বাজার, রাজশাহী',
        marketNameEn: locationData?.nameEn ?? 'Shaheb Bazar, Rajshahi',
        fairPrice: double.parse(damPrice.toStringAsFixed(1)),
        marketAvg: double.parse(marketAvg.toStringAsFixed(1)),
        minimumPrice: double.parse(minPrice.toStringAsFixed(1)),
        maximumPrice: double.parse(maxPrice.toStringAsFixed(1)),
        wholesalePrice: double.parse(wholesale.toStringAsFixed(1)),
        unitBn: p['unitBn'] as String,
        unitEn: p['unitEn'] as String,
        priceType: PriceType.retail,
        source: PriceSource.dam,
        sourceName: AppStrings.damOfficialSourceBn,
        date: date ?? now,
        lastUpdated: now.subtract(const Duration(minutes: 45)),
        isOfficial: true,
        history7d: (p['h7'] as List<double>).map((v) => v * modifier).toList(),
        history30d: (p['h30'] as List<double>).map((v) => v * modifier).toList(),
      );
    }).toList();
  }

  @override
  Future<MarketPrice?> getProductDetail(
    String productId,
    String marketId,
  ) async {
    final list = await getPrices(division: 'rajshahi', marketId: marketId);
    return list.firstWhere(
      (p) => p.productId == productId,
      orElse: () => list.first,
    );
  }
